#!/usr/bin/env python3
"""Convert the Amiga StarDust modules into SMS PSG music banks.

    python3 tools/convert_music.py /path/to/Stardust [--preview DIR]

/path/to/Stardust is the folder from Stardust.lha that holds the "p4x.*"
modules (The Player 4.x). Requires gcc, libxmp-dev (module replay) and NumPy.
Writes assets/sms/music.bin (banks MUSIC_FIRST_BANK..), src/music.h and
assets/sms/music.json. The baked outputs are committed, so a normal `make`
does not need the Amiga files or this script.

Pipeline: libxmp replays each module tick by tick (tools/music/moddump.c);
tools/music/mod2psg.py turns every 50 Hz tick into PSG register state;
tools/music/encode.py delta-encodes, substring-compresses, and the result is
decoded again here exactly like the Z80 player does, frame by frame.
"""
import sys, json, subprocess, argparse
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'tools/music'))
from mod2psg import convert, legacy_frames, render
from encode import encode_song, assemble, decode_check, BANK

FIRST_BANK = 20          # banks 2..19 hold the art
GAMEPLAY = dict(base=3, noise_base=5)    # leave head-room for sound effects
QUIET_SFX = dict(base=1, noise_base=3)   # title: no sound effects compete

# C name, module file, conversion options
TRACKS = [
    ('MUS_MENU',     None,                      None),       # original SMS tune
    ('MUS_TITLE',    'p4x.engage the scy!!!xx', QUIET_SFX),
    ('MUS_WORLD1',   'p4x.sd-ingame1',          GAMEPLAY),
    ('MUS_WORLD2',   'p4x.level2ingame',        GAMEPLAY),
    ('MUS_WORLD3',   'p4x.level3ingame',        GAMEPLAY),
    ('MUS_WORLD4',   'p4x.sd-ingametry2',       GAMEPLAY),
    ('MUS_WORLD5',   'p4x.level5ingame',        GAMEPLAY),
    ('MUS_BOSS',     'p4x.sd-boss to try2',     GAMEPLAY),   # guardians 1, 2, 4
    ('MUS_BOSS3',    'p4x.level3boss',          GAMEPLAY),   # guardian 3
    ('MUS_BOSS5',    'p4x.level5boss',          GAMEPLAY),   # egg machine
    ('MUS_FINAL',    'p4x.sd-hardcore.finboss', GAMEPLAY),   # the professor
    ('MUS_TUNNEL_A', 'p4x.sd-umpitunneli hc',   GAMEPLAY),   # tunnels 1 and 3
    ('MUS_TUNNEL_B', 'p4x.tunnel4',             GAMEPLAY),   # tunnels 2 and 4
]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('amiga_dir', help='folder containing the p4x.* modules')
    ap.add_argument('--preview', help='also render PSG previews (WAV) into this folder')
    a = ap.parse_args()
    src = Path(a.amiga_dir)
    work = ROOT / 'build/music'; work.mkdir(parents=True, exist_ok=True)
    dumper = work / 'moddump'
    subprocess.run(['gcc', '-O2', '-o', str(dumper), str(ROOT / 'tools/music/moddump.c'), '-lxmp'], check=True)
    preview = Path(a.preview) if a.preview else None
    if preview: preview.mkdir(parents=True, exist_ok=True)

    base = FIRST_BANK * BANK
    blob = bytearray(); table = []; report = []
    for cname, module, opts in TRACKS:
        if module is None:
            frames, loop = legacy_frames()
        else:
            d = work / cname.lower(); d.mkdir(exist_ok=True)
            subprocess.run([str(dumper), str(src / module), str(d)], check=True)
            frames, loop, info = convert(d, opts)
        items, loop_tok, rawsize = encode_song(frames, loop)
        start = base + len(blob)
        data, loop_off = assemble(items, start, loop_tok)
        blob += data
        table.append((cname, start, start + loop_off, frames, loop))
        report.append(dict(track=cname, source=module or 'original SMS menu tune', seconds=round(len(frames) / 50, 1),
                           loop_at_seconds=round(loop / 50, 1), raw_bytes=rawsize, packed_bytes=len(data)))
        print(f'{cname:13s} {len(frames)/50:6.1f}s loop@{loop/50:5.1f}s  {rawsize:6d} -> {len(data):6d} bytes', flush=True)
        if preview:
            render(frames, str(preview / f'{cname.lower()}.wav'))
    for cname, start, loop_abs, frames, loop in table:
        decode_check(bytes(blob), start, loop_abs, base, len(frames), frames, loop)
    nbanks = (len(blob) + BANK - 1) // BANK
    assert FIRST_BANK + nbanks <= 32, 'music no longer fits the 512 KiB cartridge'
    blob += bytes([0xff]) * (nbanks * BANK - len(blob))
    (ROOT / 'assets/sms/music.bin').write_bytes(blob)
    h = ['/* Generated by tools/convert_music.py from the Amiga StarDust modules. Do not hand-edit. */',
         '#ifndef MUSIC_H', '#define MUSIC_H',
         f'#define MUSIC_FIRST_BANK {FIRST_BANK}', f'#define MUSIC_BANKS {nbanks}', f'#define MUSIC_TRACKS {len(table)}']
    h += [f'#define {t[0]} {i}' for i, t in enumerate(table)]
    h += ['#ifdef MUSIC_TABLE', '/* stream start and loop point: bank + slot-2 address */',
          'static const u8 music_bank[MUSIC_TRACKS]={' + ','.join(str(t[1] // BANK) for t in table) + '};',
          'static const u16 music_addr[MUSIC_TRACKS]={' + ','.join(f'0x{0x8000 + t[1] % BANK:04x}' for t in table) + '};',
          'static const u8 music_loop_bank[MUSIC_TRACKS]={' + ','.join(str(t[2] // BANK) for t in table) + '};',
          'static const u16 music_loop_addr[MUSIC_TRACKS]={' + ','.join(f'0x{0x8000 + t[2] % BANK:04x}' for t in table) + '};',
          '#endif', '#endif']
    (ROOT / 'src/music.h').write_text('\n'.join(h) + '\n')
    (ROOT / 'assets/sms/music.json').write_text(json.dumps(dict(first_bank=FIRST_BANK, banks=nbanks,
                                                                used_bytes=sum(r['packed_bytes'] for r in report),
                                                                tracks=report), indent=2) + '\n')
    print(f'music.bin: {nbanks} banks ({FIRST_BANK}..{FIRST_BANK + nbanks - 1}); every stream decode-verified')


if __name__ == '__main__':
    main()
